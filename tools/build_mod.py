"""Generate hooks/register.js, the mod's one file, from hooks/src/.

The directory that reviews plugins reads the mod file by itself: it accepts `$` (the capability object)
and `on` only when they are passed to a function declared in the SAME file. So everything that touches
`$` lives in hooks/src/*.js, and this script joins those parts, in the order below, into the readable,
unminified hooks/register.js. Pure helpers that never see `$` (saver-logic, saver-i18n, compact-logic,
tidy-logic, report-logic, ask-logic, coord) stay separate files and are imported.

    python3 tools/build_mod.py          # write hooks/register.js
    python3 tools/build_mod.py --check  # fail if it is stale or two parts declare the same name (CI)
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "hooks", "src")
OUT = os.path.join(ROOT, "hooks", "register.js")
# Join order: shared helpers first, the entry (which registers every hook) last.
PARTS = ["lang", "ask", "handoff", "stats-flow", "reset-flow", "compact-flow", "tidy-flow", "register"]
BUNDLED = {f"./{p}.mjs" for p in PARTS} | {f"./{p}.js" for p in PARTS}

IMPORT = re.compile(r"^import\s*\{([^}]*)\}\s*from\s*'([^']+)'\s*\n", re.M)
DECL = re.compile(r"^(?:export\s+)?(?:async\s+)?function\s*\*?\s*(\w+)|^(?:export\s+)?(?:const|let|var)\s+(\w+)", re.M)

BANNER = """// GENERATED by tools/build_mod.py from hooks/src/*.js. Edit those files, not this one.
// (The directory that reviews plugins reads this file alone and follows `$` and `on` only into functions
// declared here, so every part that touches `$` is joined into this one readable file. Pure helpers that
// never see `$` stay in their own files and are imported below.)
"""


def build():
    imports = {}  # module -> set of names
    bodies = []
    seen = {}  # top-level name -> part
    clashes = []
    for part in PARTS:
        path = os.path.join(SRC, part + ".js")
        text = open(path, encoding="utf-8").read()

        def grab(m):
            module = m.group(2)
            if module in BUNDLED:
                return ""
            names = {n.strip() for n in m.group(1).replace("\n", " ").split(",") if n.strip()}
            imports.setdefault(module, set()).update(names)
            return ""

        body = IMPORT.sub(grab, text)
        # Parts export their functions for the bundle; only `register`, the mod's entry point, stays exported.
        body = re.sub(r"^export\s+(?!function\s+register\s*\()(async\s+function|function|const|let|class)", r"\1", body, flags=re.M)
        for m in DECL.finditer(body):
            name = m.group(1) or m.group(2)
            if name in seen and seen[name] != part:
                clashes.append(f"{name} is declared in {seen[name]} and {part}")
            seen.setdefault(name, part)
        bodies.append(f"// ===== {part} " + "=" * max(4, 70 - len(part)) + "\n" + body.strip("\n") + "\n")

    for module, names in imports.items():
        for name in names:
            if name in seen:
                clashes.append(f"{name} is imported from {module} and declared in {seen[name]}")
    head = BANNER
    for module in sorted(imports):
        names = sorted(imports[module])
        head += "import {\n" + "".join(f"  {n},\n" for n in names) + f"}} from '{module}'\n"
    return head + "\n" + "\n".join(bodies), clashes


def foreign_dollar_calls(text):
    """Calls that pass `$` to a function that is not declared in the file (the directory rejects these)."""
    declared = set(re.findall(r"^(?:async\s+)?function\s*\*?\s*(\w+)", text, re.M))
    skip = {"if", "for", "while", "catch", "function", "async", "await", "switch", "return"}
    found = set()
    for m in re.finditer(r"(\w+)\(([^()]*\$[,)][^()]*)\)", text):
        if m.group(1) not in declared and m.group(1) not in skip:
            found.add(m.group(1))
    return sorted(found)


def main():
    out, clashes = build()
    clashes += [f"$ is passed to {n}, which is not declared in hooks/register.js" for n in foreign_dollar_calls(out)]
    if clashes:
        sys.exit("name clashes:\n  " + "\n  ".join(sorted(set(clashes))))
    if "--check" in sys.argv:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if current != out:
            sys.exit("hooks/register.js is stale: run python3 tools/build_mod.py")
        print("hooks/register.js up to date")
        return
    open(OUT, "w", encoding="utf-8").write(out)
    print("wrote hooks/register.js", len(out.splitlines()), "lines")


main()
